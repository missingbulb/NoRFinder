// Under Node, the decoders the page imports from jsDelivr resolve to web-tests/node_modules instead, where the full
// CI set installs them at the same versions. Imported before the page's modules.
import { register } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const modules = pathToFileURL(path.join(path.dirname(fileURLToPath(import.meta.url)), "node_modules")).href + "/";
register("data:text/javascript," + encodeURIComponent(`
const CDN = "https://cdn.jsdelivr.net/npm/", HERE = ${JSON.stringify(modules)};
export async function resolve(spec, ctx, next) {
  return spec.startsWith(CDN) ? { url: HERE + spec.slice(CDN.length).replace(/@[^/]+/, ""), shortCircuit: true } : next(spec, ctx);
}`));
